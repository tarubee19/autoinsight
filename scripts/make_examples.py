"""Regenerate the committed example outputs in ./examples (reports, charts, the self-repair trace).

    python scripts/make_examples.py

Everything runs offline (no API key). Models and cleaned data are not copied to keep the repo small.
"""

from __future__ import annotations

import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import pandas as pd  # noqa: E402

from autoinsight.config import Settings  # noqa: E402
from autoinsight.pipeline import run_pipeline  # noqa: E402
from autoinsight.sandbox import Sandbox  # noqa: E402
from autoinsight.testing import (  # noqa: E402
    RUNTIME_BUG,
    UNSAFE_CODE,
    ScriptedLLM,
    engineer_template,
)

OUT = ROOT / "examples"
KEEP = ["report.md", "report.html", "stats.json", "metrics.json", "cleaning_log.json", "schema.json", "feature_importance.json"]


def copy_run(run_dir: Path, name: str) -> None:
    dest = OUT / name
    shutil.rmtree(dest, ignore_errors=True)
    (dest / "charts").mkdir(parents=True)
    art = run_dir / "artifacts"
    for f in KEEP:
        shutil.copyfile(art / f, dest / f)
    for png in (art / "charts").glob("*.png"):
        shutil.copyfile(png, dest / "charts" / png.name)


def self_repair_trace(tmp: Path) -> str:
    """Generate a self-repair trace for the given temporary directory."""
    csv = tmp / "churn_800.csv"
    pd.read_csv(ROOT / "data" / "sample" / "telco_churn.csv").head(800).to_csv(csv, index=False)
    settings = Settings(llm_provider="offline", sandbox_mode="local", runs_dir=tmp / "trace", allow_unsafe_local=True)
    llm = ScriptedLLM(engineer=[UNSAFE_CODE, RUNTIME_BUG, engineer_template])
    events: list[dict] = []
    res = run_pipeline(csv, "Find the driving factors behind customer churn", settings=settings, llm=llm,
                       sandbox=Sandbox(settings, mode="local"), on_event=events.append, keep_work_dir=False)  # fmt: skip
    lines = [
        "# Self-repair trace (real output)",
        "",
        "A scripted 'LLM' is made to write **unsafe code**, then **buggy code**, then correct code for the Data Engineer.",
        "This is what the workflow did - generated by `python scripts/make_examples.py`.",
        "",
        "## Agent events",
        "",
        "```text",
    ]
    for e in events:
        lines.append(f"[{e['agent']:<9}] {e['status']:<6} {e['message'][:140]}")
    lines += ["```", "", "## What each failed attempt told the agent", ""]
    for p in sorted((res.run_dir / "logs").glob("engineer_attempt*.json")):
        log = json.loads(p.read_text())
        lines += [f"### Attempt {log['attempt']} - {'OK' if log['ok'] else 'FAILED'} (source: {log['source']})", ""]
        if log["error"]:
            lines += ["```text", log["error"].strip()[:700], "```", ""]
        else:
            lines += ["Output passed the contract checks (cleaned.csv + cleaning_log.json valid).", ""]
    lines += [
        "## Outcome", "",
        f"Run status: **{res.status}** - attempts per agent: `{res.summary['attempts']}`. "
        "The unsafe program was rejected by the AST guard *before* it could run; the buggy one failed inside the sandbox; "
        "the third attempt succeeded and the rest of the workflow continued normally.",
        "",
    ]  # fmt: skip
    return "\n".join(lines)


def main() -> None:
    OUT.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="autoinsight-examples-") as tmp_name:
        tmp = Path(tmp_name)
        for name, csv, question in [
            ("telco_churn", "telco_churn.csv", "Find the driving factors behind customer churn"),
            ("house_prices", "house_prices.csv", "What drives the sale price of a house?"),
        ]:
            settings = Settings(llm_provider="offline", sandbox_mode="local", runs_dir=tmp / name)
            res = run_pipeline(ROOT / "data" / "sample" / csv, question, settings=settings)
            assert res.ok, res.error
            copy_run(res.run_dir, name)
            print("example written:", name)
        (OUT / "self_repair_trace.md").write_text(self_repair_trace(tmp), encoding="utf-8")
        print("example written: self_repair_trace.md")


if __name__ == "__main__":
    main()

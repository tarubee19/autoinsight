"""Render docs/REAL_DATA_BENCHMARK.md and docs/assets/real_data_model_zoo.png from docs/real_data_benchmark.json.

Every number in the markdown comes from the json written by scripts/benchmark_real_data.py.
The "before" column comes from docs/real_data_benchmark_before.json (same script, run before the
modeler changes in this commit) when it exists.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
NAMES = {"telco_churn_ibm": "IBM Telco churn", "hr_attrition_ibm": "IBM HR attrition",
         "ames_housing": "Ames housing", "bank_marketing": "UCI bank marketing"}
BLUE, ORANGE, MUTED, GRID, INK, SURF = "#2a78d6", "#eb6834", "#52514e", "#e6e5e1", "#0b0b0b", "#fcfcfb"


def fmt_p(p):
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def main():
    res = json.loads((DOCS / "real_data_benchmark.json").read_text())
    before_path = DOCS / "real_data_benchmark_before.json"
    before = json.loads(before_path.read_text()) if before_path.exists() else {}
    L = ["# Real-data benchmark", "",
         "_Generated by `scripts/render_real_benchmark.py` from `docs/real_data_benchmark.json` "
         "(produced by `python scripts/benchmark_real_data.py`; offline mode, seed 42)._", "",
         "The synthetic evaluation (docs/EVALUATION.md) shows the pipeline *works*. This one asks whether it holds up on "
         "public real datasets it was never tuned on, and whether its model choices are justified.", "",
         "## 1. End-to-end runs (raw CSV + plain-English question, no target given)", "",
         "| Dataset | Rows | Target picked | Model chosen (CV) | Held-out score | Before this change | Report numbers verified | Run time |",
         "|---|---|---|---|---|---|---|---|"]
    for k, v in res.items():
        e = v["e2e"]
        b = before.get(k, {}).get("e2e", {})
        bscore = f"{b['model']}, {b['score']:.3f}" if b.get("score") else ("failed: " + (b.get("error") or "")[:70] if b else "-")
        rows = v["zoo"]["rows"] if v.get("zoo") else "?"
        g = e.get("grounding_rate")
        L.append(f"| {NAMES[k]} | {rows:,} | `{e['target']}` {'(correct)' if e.get('target_correct') else '(WRONG)'} | "
                 f"{e.get('model')} | {e.get('metric')} {e['score']:.3f} | {bscore} | "
                 f"{'' if g is None else f'{g:.0%} of {e.get('numbers_checked')}'} | {e['seconds']:.0f} s |")
    L += ["", "## 2. Model zoo: 5-fold x 3-repeat cross-validation on the cleaned data", "",
          "Same folds for every model. `p` = Nadeau-Bengio corrected resampled t-test against the best of the "
          "modeler's original candidates (plain paired t-tests on CV folds are over-confident because the training "
          "sets overlap).", ""]
    for k, v in res.items():
        for key, title in (("zoo", ""), ("zoo_without_duration", " - without `duration` (leakage check)")):
            z = v.get(key)
            if not z:
                continue
            L += [f"### {NAMES[k]}{title}", "", f"{z['rows']:,} rows x {z['features']} features. Reference: {z['reference_model']}.", "",
                  f"| Model | {z['metric']} (mean +/- sd) | {z['secondary_metric']} | Fit time | Diff vs reference | p |",
                  "|---|---|---|---|---|---|"]
            for m, r in sorted(z["models"].items(), key=lambda kv: -kv[1]["mean"]):
                vs = r["vs_current_best"]
                sec = f"{r['secondary']:,.0f}" if z["secondary_metric"] == "MAE" else f"{r['secondary']:.3f}"
                L.append(f"| {m} | {r['mean']:.4f} +/- {r['std']:.4f} | {sec} | {r['fit_s']:.2f} s | "
                         f"{'-' if vs is None else f'{vs['diff']:+.4f}'} | {'-' if vs is None else fmt_p(vs['p_value'])} |")
            L += ["", f"_{v['reference']}_" if key == "zoo" else "", ""]
    (DOCS / "REAL_DATA_BENCHMARK.md").write_text("\n".join(L))

    # ---- figure: one panel per dataset, models as dots with +/- 1 sd
    fig, axes = plt.subplots(1, 4, figsize=(13, 3.6), facecolor=SURF)
    for ax, (k, v) in zip(axes, res.items()):
        z = v["zoo"]
        items = [(m, r) for m, r in z["models"].items() if not m.startswith("baseline")]
        items.sort(key=lambda t: t[1]["mean"])
        for i, (m, r) in enumerate(items):
            c = BLUE if "(current)" in m else ORANGE
            ax.errorbar(r["mean"], i, xerr=r["std"], fmt="o", color=c, ecolor=GRID, elinewidth=2, ms=6)
        ax.set_yticks(range(len(items)))
        ax.set_yticklabels([m.replace(" (current)", "*") for m, _ in items], fontsize=8)
        ax.set_title(NAMES[k], loc="left", fontsize=10, fontweight="bold", color=INK)
        ax.set_xlabel(z["metric"], color=MUTED)
        ax.set_facecolor(SURF)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
        ax.grid(axis="x", color=GRID)
    fig.suptitle("Cross-validated score by model (* = in the original modeler; orange = added for comparison)",
                 x=0.01, ha="left", fontsize=10, color=MUTED)
    fig.tight_layout()
    (DOCS / "assets").mkdir(exist_ok=True)
    fig.savefig(DOCS / "assets" / "real_data_model_zoo.png", dpi=150, facecolor=SURF)
    print("wrote", DOCS / "REAL_DATA_BENCHMARK.md")


if __name__ == "__main__":
    main()
